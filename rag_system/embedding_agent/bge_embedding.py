import os
import logging
from typing import Any

from dotenv import load_dotenv
from huggingface_hub import InferenceClient


# ============================================================
# CONFIGURATION
# ============================================================

load_dotenv()

MODEL = "BAAI/bge-m3"

logger = logging.getLogger(__name__)


# ============================================================
# CREATE EMBEDDING MODEL CLIENT
# ============================================================

def embedding_model() -> InferenceClient:
    """
    Create the Hugging Face inference client used for
    BGE-M3 embeddings.

    Returns:
        InferenceClient: Hugging Face inference client.
    """

    hf_token = os.getenv("HF_TOKEN")

    if not hf_token:
        raise ValueError(
            "HF_TOKEN is not configured in the environment."
        )

    return InferenceClient(
        provider="hf-inference",
        api_key=hf_token,
    )


# ============================================================
# EMBED SINGLE TEXT
# ============================================================

def embed_text(
    text: str,
    client: InferenceClient,
) -> Any:
    """
    Generate a BGE-M3 embedding for a single text.

    Args:
        text: Text that needs to be embedded.
        client: Hugging Face inference client.

    Returns:
        Embedding vector.
    """

    if not text or not text.strip():
        raise ValueError("Text cannot be empty.")

    try:

        embedding = client.feature_extraction(
            text.strip(),
            model=MODEL,
        )

        return embedding

    except Exception as error:

        logger.error(
            "Text embedding failed | error=%s",
            error,
            exc_info=True,
        )

        raise


# ============================================================
# EMBED ALL CHUNKS
# ============================================================

def file_embed(
    all_chunks: list[dict],
) -> list[dict]:
    """
    Generate BGE-M3 embeddings for all document chunks.

    The original chunk information is preserved and the
    generated embedding is attached to each chunk.

    Args:
        all_chunks: List of chunks generated by HybridChunker.

    Returns:
        List of chunks containing their embeddings.
    """

    if not all_chunks:

        logger.warning(
            "No chunks received for embedding."
        )

        return []

    client = embedding_model()

    embedded_chunks = []

    logger.info(
        "Embedding started | total_chunks=%d | model=%s",
        len(all_chunks),
        MODEL,
    )

    for chunk in all_chunks:

        chunk_index = chunk.get("chunk_index")
        text = chunk.get("text")

        if not text or not text.strip():

            logger.warning(
                "Skipping empty chunk | chunk_index=%s",
                chunk_index,
            )

            continue

        try:

            logger.info(
                "Embedding chunk | chunk_index=%s",
                chunk_index,
            )

            embedding = embed_text(
                text=text,
                client=client,
            )

            embedded_chunk = {
                **chunk,
                "embedding": embedding,
            }

            embedded_chunks.append(
                embedded_chunk
            )

        except Exception as error:

            logger.error(
                "Embedding failed | chunk_index=%s | error=%s",
                chunk_index,
                error,
                exc_info=True,
            )

            raise

    logger.info(
        "Embedding completed | successful=%d | failed=%d",
        len(embedded_chunks),
        len(all_chunks) - len(embedded_chunks),
    )

    return embedded_chunks